// FUNCTION 4 - saved report exports (CSV in S3, metadata in PostgreSQL).
// Ownership: staff can only see / download / delete their own exports. Admin can manage all.
const crypto = require('crypto');
const { query } = require('../../db/pool');
const { HttpError } = require('../../utils/httpError');
const { toCsv } = require('../../utils/csv');
const { MAX_EXPORTS_PER_USER } = require('../../constants');
const storage = require('../../aws/s3Storage');
const reportService = require('./reportService');
const logger = require('../../utils/logger');

async function createExport(user, type, filters) {
  // Business limit: stops one account filling the bucket (cost control).
  const { rows: countRows } = await query('SELECT COUNT(*) AS n FROM saved_reports WHERE owner_user_id = $1', [user.id]);
  if (countRows[0].n >= MAX_EXPORTS_PER_USER) {
    throw new HttpError(409, `You already have ${MAX_EXPORTS_PER_USER} saved exports. Delete some before creating more.`);
  }

  const { columns, rows } = await reportService.detailRows(type, filters);
  const csv = toCsv(columns, rows);
  // The key is generated by the server (never taken from the user), so nobody can write to another user's folder.
  const key = `reports/user-${user.id}/${type}-${new Date().toISOString().slice(0, 10)}-${crypto.randomUUID()}.csv`;
  await storage.putReport(key, csv);

  try {
    const { rows: saved } = await query(
      `INSERT INTO saved_reports (owner_user_id, report_type, filters, s3_key, row_count, size_bytes)
       VALUES ($1, $2, $3, $4, $5, $6)
       RETURNING report_id, owner_user_id, report_type, filters, row_count, size_bytes, created_at`,
      [user.id, type, JSON.stringify(filters), key, rows.length, Buffer.byteLength(csv)]
    );
    logger.info('REPORT_EXPORTED', { userId: user.id, reportId: saved[0].report_id, type, rows: rows.length });
    return saved[0];
  } catch (err) {
    await storage.deleteReport(key).catch(() => {}); // don't leave an orphan file in S3
    throw err;
  }
}

async function listExports(user) {
  // Admin sees everyone's exports; staff only their own. The filter is in the SQL itself.
  const isAdmin = user.role === 'admin';
  const { rows } = await query(
    `SELECT r.report_id, r.owner_user_id, u.name AS owner_name, r.report_type, r.filters, r.row_count, r.size_bytes, r.created_at
     FROM saved_reports r JOIN users u ON u.user_id = r.owner_user_id
     WHERE ($1::boolean OR r.owner_user_id = $2)
     ORDER BY r.created_at DESC LIMIT 200`,
    [isAdmin, user.id]
  );
  return rows;
}

// Loads one export and enforces the ownership rule.
async function getOwnedExport(user, reportId) {
  const { rows } = await query('SELECT report_id, owner_user_id, report_type, s3_key, created_at FROM saved_reports WHERE report_id = $1', [reportId]);
  const report = rows[0];
  if (!report) throw new HttpError(404, 'Report not found');
  if (report.owner_user_id !== user.id && user.role !== 'admin') {
    logger.warn('ACCESS_DENIED_OWNERSHIP', { userId: user.id, reportId, ownerId: report.owner_user_id, status: 403 });
    throw new HttpError(403, 'You can only access your own reports');
  }
  return report;
}

async function downloadLink(user, reportId) {
  const report = await getOwnedExport(user, reportId);
  const filename = `${report.report_type}-report-${report.report_id}.csv`;
  const url = await storage.signedDownloadUrl(report.s3_key, filename, 300);
  logger.info('REPORT_DOWNLOAD_LINK', { userId: user.id, reportId });
  return { url, expires_in_seconds: 300 };
}

async function deleteExport(user, reportId) {
  const report = await getOwnedExport(user, reportId);
  await storage.deleteReport(report.s3_key);
  await query('DELETE FROM saved_reports WHERE report_id = $1', [reportId]);
  logger.info('REPORT_DELETED', { userId: user.id, reportId });
}

module.exports = { createExport, listExports, downloadLink, deleteExport };
